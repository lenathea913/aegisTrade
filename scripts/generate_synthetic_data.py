"""Generate deterministic synthetic OHLCV data for the demo backtest.

The series is a random walk with a slow sinusoidal drift, seeded so the file can be
regenerated byte-for-byte. It is **not** market data and carries no signal; it exists
so the backtest engine and the EMA demo strategy have something reproducible to run on.

Usage:
    python scripts/generate_synthetic_data.py [--bars 1500] [--seed 42] [--out PATH]
"""

from __future__ import annotations

import argparse
import csv
import math
import random
from datetime import UTC, datetime, timedelta
from pathlib import Path

DEFAULT_OUT = Path("data/seeds/BTCUSDT_1h.csv")
START = datetime(2024, 1, 1, tzinfo=UTC)
START_PRICE = 30_000.0


def generate_rows(bars: int, seed: int) -> list[tuple[datetime, float, float, float, float, float]]:
    rng = random.Random(seed)
    price = START_PRICE
    rows: list[tuple[datetime, float, float, float, float, float]] = []
    timestamp = START

    for index in range(bars):
        drift = 0.0006 * math.sin(index / 60.0) + 0.00002
        open_price = price
        close_price = max(1.0, open_price * (1.0 + drift + rng.gauss(0.0, 0.004)))
        high = max(open_price, close_price) * (1.0 + abs(rng.gauss(0.0, 0.002)))
        low = min(open_price, close_price) * (1.0 - abs(rng.gauss(0.0, 0.002)))
        volume = rng.uniform(50.0, 500.0)

        rows.append((timestamp, open_price, high, low, close_price, volume))
        price = close_price
        timestamp += timedelta(hours=1)

    return rows


def write_csv(path: Path, rows: list[tuple[datetime, float, float, float, float, float]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["open_time", "open", "high", "low", "close", "volume"])
        for timestamp, open_price, high, low, close_price, volume in rows:
            writer.writerow(
                [
                    timestamp.strftime("%Y-%m-%dT%H:%M:%SZ"),
                    f"{open_price:.8f}",
                    f"{high:.8f}",
                    f"{low:.8f}",
                    f"{close_price:.8f}",
                    f"{volume:.8f}",
                ]
            )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bars", type=int, default=1500)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    rows = generate_rows(args.bars, args.seed)
    write_csv(args.out, rows)
    print(f"wrote {len(rows)} synthetic bars to {args.out} (seed={args.seed})")


if __name__ == "__main__":
    main()
